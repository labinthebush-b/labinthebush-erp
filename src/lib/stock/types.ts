// Domain types for the Estoque module (T5.5).
//
// Stock is never stored as a number: it is the SUM of StockMovements for a
// variant — the (size, color) pair of a product. This mirrors how a Sale feeds
// the Financeiro: a sale item generates its own "saída" movement, and editing or
// deleting the sale updates or removes it, so there is no balance that can
// drift away from its history.

export type StockMovementKind = "entrada" | "saida" | "ajuste";

export type StockMovement = {
  id: string;
  productId: string;
  /** Absent when the product has no sizes (a single variant). */
  size?: string;
  /** Absent when the product has no colors. */
  color?: string;
  /** Signed, never zero: positive adds pieces to stock, negative removes them. */
  quantity: number;
  kind: StockMovementKind;
  date: string; // ISO yyyy-MM-dd
  note?: string;
  /** Set only on the "saída" generated by a sale. */
  saleId?: string;
  saleItemId?: string;
  createdAt: string;
  updatedAt: string;
};

/** One sellable variant of a product. Both fields are absent for a product with no sizes/colors. */
export type VariantRef = {
  productId: string;
  size?: string;
  color?: string;
};

export type StockLevelStatus = "ok" | "baixo" | "esgotado";
